/**
 * Numberblocks Band Creator - Canvas & Audio Recording Engine
 * Automatically binds to GDevelop's runtime environment.
 */

window.BandRecorder = {
    mediaRecorder: null,
    recordedChunks: [],
    audioContext: null,
    destNode: null,

    /**
     * Initializes the Web Audio capture connection. 
     * Run this once at the beginning of the scene.
     */
    initAudioCapture: function() {
        try {
            // Locates the active audio engine context used by GDevelop/Howler
            const gdAudio = window.Howler || null;
            this.audioContext = gdAudio ? gdAudio.ctx : (window.AudioContext || window.webkitAudioContext ? new (window.AudioContext || window.webkitAudioContext)() : null);
            
            if (this.audioContext) {
                // Creates a secondary audio output stream specifically for the video file recorder
                this.destNode = this.audioContext.createMediaStreamDestination();
                console.log("Audio capture pipeline established.");
            }
        } catch (e) {
            console.error("Failed to initialize audio routing:", e);
        }
    },

    /**
     * Starts capturing the game screen canvas.
     * @param {number} fps - Framerate target (30 is highly recommended for mobile stability).
     */
    startRecording: function(fps = 30) {
        this.recordedChunks = [];
        
        // Target the main rendering canvas element generated by GDevelop
        const canvas = document.getElementById('lm-canvas') || document.querySelector('canvas');
        
        if (!canvas) {
            console.error("GDevelop render canvas not found.");
            return;
        }

        // 1. Capture the visual frame stream from the canvas
        const videoStream = canvas.captureStream(fps);
        const combinedStream = new MediaStream();

        // Feed the visual tracks into our master output file stream
        videoStream.getVideoTracks().forEach(track => combinedStream.addTrack(track));

        // 2. Mix in the audio track if the audio destination node is active
        if (this.destNode && this.destNode.stream.getAudioTracks().length > 0) {
            this.destNode.stream.getAudioTracks().forEach(track => combinedStream.addTrack(track));
        }

        // 3. Select the safest recording file container for mobile browsers/webviews
        let options = { mimeType: 'video/webm; codecs=vp9,opus' };
        if (!MediaRecorder.isTypeSupported(options.mimeType)) {
            options = { mimeType: 'video/webm; codecs=vp8,opus' };
            if (!MediaRecorder.isTypeSupported(options.mimeType)) {
                options = { mimeType: 'video/mp4' }; // Fallback for iOS configurations
            }
        }

        try {
            this.mediaRecorder = new MediaRecorder(combinedStream, options);
            
            this.mediaRecorder.ondataavailable = (event) => {
                if (event.data && event.data.size > 0) {
                    this.recordedChunks.push(event.data);
                }
            };

            this.mediaRecorder.onstop = () => {
                this.compileAndDownload();
            };

            // Capture data blocks continuously every 10ms to keep mobile RAM usage low
            this.mediaRecorder.start(10); 
            console.log("Recording stream initialized profile: " + options.mimeType);
        } catch (err) {
            console.error("Could not launch MediaRecorder wrapper:", err);
        }
    },

    /**
     * Halts the active stream capture and initiates file creation.
     */
    stopRecording: function() {
        if (this.mediaRecorder && this.mediaRecorder.state !== "inactive") {
            this.mediaRecorder.stop();
            console.log("Recording process stopped.");
        }
    },

    /**
     * Compiles the stored video chunks and triggers a native mobile download prompt.
     */
    compileAndDownload: function() {
        if (this.recordedChunks.length === 0) return;

        const blobType = this.mediaRecorder.mimeType || 'video/webm';
        const videoBlob = new Blob(this.recordedChunks, { type: blobType });
        const downloadUrl = URL.createObjectURL(videoBlob);
        
        const anchor = document.createElement('a');
        anchor.href = downloadUrl;
        
        // Assign the correct file extension base matching the encoding platform
        const extension = blobType.includes('mp4') ? 'mp4' : 'webm';
        anchor.download = `numberblocks_band_${Date.now()}.${extension}`;
        
        document.body.appendChild(anchor);
        anchor.click();
        
        // Instantly clean up working memory structures to prevent mobile system crashes
        setTimeout(() => {
            document.body.removeChild(anchor);
            window.URL.revokeObjectURL(downloadUrl);
        }, 100);
    }
};

